// Packs assets/gradient.png and every assets/overlays/*.png into assets/embedded.js
// as data URIs, so index.html works straight from disk (file://) without a server.
// Run after adding or changing a PNG:  node scripts/embed-assets.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataUri = (p) => 'data:image/png;base64,' + readFileSync(p).toString('base64');

const overlays = {};
for (const f of readdirSync(join(root, 'assets/overlays')).sort()) {
  if (f.toLowerCase().endsWith('.png')) overlays[basename(f, '.png')] = dataUri(join(root, 'assets/overlays', f));
}

const out = {
  gradient: dataUri(join(root, 'assets/gradient.png')),
  overlays,
};
writeFileSync(
  join(root, 'assets/embedded.js'),
  '// Generated by scripts/embed-assets.mjs — do not edit by hand.\nwindow.THUMB_ASSETS = ' + JSON.stringify(out) + ';\n',
);
console.log('embedded gradient + overlays:', Object.keys(overlays).join(', '));
