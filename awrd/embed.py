"""Packs awrd/assets into assets/embedded.js so index.html opens from disk.  python3 awrd/embed.py"""
import base64, json
from pathlib import Path
A = Path(__file__).resolve().parent / "assets"
mime = {".png": "image/png", ".woff2": "font/woff2"}
data = {p.stem: f"data:{mime[p.suffix]};base64," + base64.b64encode(p.read_bytes()).decode()
        for p in sorted(A.iterdir()) if p.suffix in mime}
(A / "embedded.js").write_text("// Generated by awrd/embed.py — do not edit by hand.\nwindow.AWRD = " + json.dumps(data) + ";\n")
print("embedded", ", ".join(data))
