"""Packs systemmap/assets/*.png + blocks.json into assets/embedded.js so
index.html works straight from disk.   python3 systemmap/embed.py"""
import base64, json
from pathlib import Path
A = Path(__file__).resolve().parent / "assets"
imgs = {p.stem: "data:image/png;base64," + base64.b64encode(p.read_bytes()).decode() for p in sorted(A.glob("*.png"))}
blocks = json.loads((A / "blocks.json").read_text())
(A / "embedded.js").write_text("// Generated by systemmap/embed.py — do not edit by hand.\nwindow.MAP_ASSETS = "
                               + json.dumps({"images": imgs, "blocks": blocks}) + ";\n")
print("embedded", ", ".join(imgs))
