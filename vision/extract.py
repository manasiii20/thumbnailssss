"""Cuts the raster pieces for the Vision Health reel out of the design captures.

    python3 vision/extract.py

Everything with text, bars, buttons or simple shapes is rebuilt as vector UI in
index.html. Only the drawn artwork is cut from the captures in vision/source/:
the activity icons, the smartwatch, the doctor portraits and the Eye Health
Education illustrations. Each piece is found as the white tile it sits on,
trimmed inside the tile's rounded corners, upscaled 2x with Lanczos and written
to vision/assets/, then everything is packed into assets/embedded.js so
index.html opens straight from disk.
"""
import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "source"
OUT = ROOT / "assets"
OUT.mkdir(exist_ok=True)


def white_tile(img, box, inset=3):
    """Bounding box of the white tile inside `box` (rec px), inset past its corners."""
    x0, y0, x1, y1 = box
    a = np.asarray(img.convert("RGB").crop(box)).astype(int)
    white = (a.min(axis=2) > 246)
    cols = np.where(white.mean(axis=0) > 0.55)[0]
    rows = np.where(white.mean(axis=1) > 0.55)[0]
    return (x0 + cols[0] + inset, y0 + rows[0] + inset, x0 + cols[-1] + 1 - inset, y0 + rows[-1] + 1 - inset)


def save(img, box, name, scale=2.0):
    piece = img.convert("RGB").crop(box)
    piece = piece.resize((round(piece.width * scale), round(piece.height * scale)), Image.LANCZOS)
    piece.save(OUT / f"{name}.png")


# Screen recording frames (412 x 828; the screen is ~364 px wide, 0.93x of 390 pt).
LIST_Y = [393, 483, 573, 663]   # the four list rows on the activity pages
for src, big, names in [
    ("rec-eye-exercises.png", "kaleidoscope", ["palming", "lazy-eye", "eye-muscle", "closed-eye"]),
    ("rec-eye-tests.png", "okn", ["snellen", "color-blindness", "landolt", "astigmatism"]),
    ("rec-eye-games.png", None, ["match-tiles", "odd-one-out", "color-cube", "speed-reading"]),
]:
    im = Image.open(SRC / src)
    if big:
        save(im, white_tile(im, (60, 174, 132, 246)), big)
    for y, n in zip(LIST_Y, names):
        save(im, white_tile(im, (58, y - 4, 124, y + 60)), n)

im = Image.open(SRC / "rec-devices-connected.png")
save(im, (250, 428, 356, 550), "watch")

im = Image.open(SRC / "rec-consultation.png")
for y, n in zip([240, 403, 566], ["dr-ayesha", "dr-rohit", "dr-priya"]):
    save(im, white_tile(im, (64, y - 6, 164, y + 96)), n)

# Eye Health Education artwork, from the activities sheet (screens ~258 px wide).
im = Image.open(SRC / "activities.png")
k = 0
for y in [160, 314, 468]:
    for x in [919, 1038]:
        k += 1
        save(im, white_tile(im, (x - 6, y - 6, x + 92, y + 58), inset=2), f"edu-{k}", scale=2.5)

mime = {".png": "image/png"}
data = {p.stem: f"data:{mime[p.suffix]};base64," + base64.b64encode(p.read_bytes()).decode()
        for p in sorted(OUT.iterdir()) if p.suffix in mime}
(OUT / "embedded.js").write_text("// Generated by vision/extract.py — do not edit by hand.\nwindow.VH = " + json.dumps(data) + ";\n")
print("embedded", ", ".join(data))
